-- =====================================================================
-- BD QuickMart — V2: Phase 1 commerce schema
-- ---------------------------------------------------------------------
-- Applied by Flyway as a SEPARATE step with the DDL migration role, exactly
-- like V1. The runtime application never runs migrations.
--
-- Design rules (same as V1):
--   * Internal PKs are BIGINT IDENTITY; external IDs are VARCHAR(36) UUIDs.
--   * All timestamps are TIMESTAMPTZ (UTC instants).
--   * Monetary values are NUMERIC(12,2), never floating point.
--   * Stock mutations are versioned so optimistic locking + SELECT FOR UPDATE
--     can guarantee consistency during concurrent order placement.
--   * Order status values are CHECK-constrained to the canonical lifecycle
--     shared by all three clients.
-- =====================================================================

SET search_path = public;

-- ---------------------------------------------------------------------
-- categories
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id    VARCHAR(36)  NOT NULL,
    name         VARCHAR(120) NOT NULL,
    description  VARCHAR(500),
    image_url    VARCHAR(500),
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    version      BIGINT       NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL,
    updated_at   TIMESTAMPTZ  NOT NULL,
    deleted_at   TIMESTAMPTZ,

    CONSTRAINT uk_categories_public_id UNIQUE (public_id),
    CONSTRAINT uk_categories_name      UNIQUE (name)
);

CREATE INDEX idx_categories_active ON categories (is_active) WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------
-- products
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id       VARCHAR(36)  NOT NULL,
    name            VARCHAR(180) NOT NULL,
    description     VARCHAR(1000),
    sku             VARCHAR(64),
    category_id     BIGINT,
    base_price      NUMERIC(12,2) NOT NULL,
    discount_price  NUMERIC(12,2),
    image_url       VARCHAR(500),
    is_available    BOOLEAN      NOT NULL DEFAULT TRUE,
    version         BIGINT       NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    deleted_at      TIMESTAMPTZ,

    CONSTRAINT uk_products_public_id UNIQUE (public_id),
    CONSTRAINT uk_products_sku       UNIQUE (sku),
    CONSTRAINT ck_products_price     CHECK (base_price >= 0),
    CONSTRAINT ck_products_discount  CHECK (discount_price IS NULL OR discount_price >= 0),
    CONSTRAINT fk_products_category  FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE SET NULL
);

CREATE INDEX idx_products_category  ON products (category_id);
CREATE INDEX idx_products_available ON products (is_available) WHERE deleted_at IS NULL;
CREATE INDEX idx_products_name      ON products (lower(name));

-- ---------------------------------------------------------------------
-- inventory — one row per product
-- ---------------------------------------------------------------------
CREATE TABLE inventory (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT      NOT NULL,
    quantity_on_hand  INTEGER     NOT NULL DEFAULT 0,
    reorder_threshold INTEGER     NOT NULL DEFAULT 5,
    version           BIGINT      NOT NULL DEFAULT 0,
    updated_at        TIMESTAMPTZ NOT NULL,

    CONSTRAINT uk_inventory_product UNIQUE (product_id),
    CONSTRAINT ck_inventory_qty     CHECK (quantity_on_hand >= 0),
    CONSTRAINT ck_inventory_threshold CHECK (reorder_threshold >= 0),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE INDEX idx_inventory_low ON inventory (quantity_on_hand, reorder_threshold);

-- Immutable audit trail for every stock change. Never updated or deleted.
CREATE TABLE inventory_adjustments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id     VARCHAR(36)  NOT NULL,
    product_id    BIGINT       NOT NULL,
    delta         INTEGER      NOT NULL,
    quantity_after INTEGER     NOT NULL,
    reason        VARCHAR(40)  NOT NULL,
    reference     VARCHAR(80),
    created_at    TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_inventory_adjustments_public_id UNIQUE (public_id),
    CONSTRAINT fk_inventory_adj_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE INDEX idx_inventory_adj_product ON inventory_adjustments (product_id, created_at DESC);

-- ---------------------------------------------------------------------
-- orders
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id         VARCHAR(36)  NOT NULL,
    idempotency_key   VARCHAR(80)  NOT NULL,
    customer_id       BIGINT       NOT NULL,
    rider_id          BIGINT,
    status            VARCHAR(32)  NOT NULL,
    payment_method    VARCHAR(24)  NOT NULL,
    delivery_address  VARCHAR(500) NOT NULL,
    contact_phone     VARCHAR(32)  NOT NULL,
    notes             VARCHAR(500),
    subtotal_amount   NUMERIC(12,2) NOT NULL,
    discount_amount   NUMERIC(12,2) NOT NULL DEFAULT 0,
    delivery_fee      NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_amount      NUMERIC(12,2) NOT NULL,
    assigned_at       TIMESTAMPTZ,
    picked_up_at      TIMESTAMPTZ,
    delivered_at      TIMESTAMPTZ,
    version           BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_orders_public_id       UNIQUE (public_id),
    CONSTRAINT uk_orders_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_orders_status CHECK (status IN
        ('PENDING','CONFIRMED','PREPARING','READY_FOR_PICKUP','ASSIGNED',
         'PICKED_UP','OUT_FOR_DELIVERY','DELIVERED','CANCELLED','REJECTED','FAILED_DELIVERY')),
    CONSTRAINT ck_orders_payment CHECK (payment_method IN ('COD')),
    CONSTRAINT ck_orders_totals CHECK (subtotal_amount >= 0 AND discount_amount >= 0
        AND delivery_fee >= 0 AND total_amount >= 0),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_rider FOREIGN KEY (rider_id)
        REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_orders_customer ON orders (customer_id, created_at DESC);
CREATE INDEX idx_orders_status   ON orders (status, created_at DESC);
CREATE INDEX idx_orders_rider    ON orders (rider_id, status);

-- ---------------------------------------------------------------------
-- order_items — price/name snapshots so history survives product edits
-- ---------------------------------------------------------------------
CREATE TABLE order_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT        NOT NULL,
    product_id         BIGINT        NOT NULL,
    product_public_id  VARCHAR(36)   NOT NULL,
    product_name       VARCHAR(180)  NOT NULL,
    unit_price         NUMERIC(12,2) NOT NULL,
    quantity           INTEGER       NOT NULL,
    line_total         NUMERIC(12,2) NOT NULL,

    CONSTRAINT ck_order_items_qty   CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price CHECK (unit_price >= 0 AND line_total >= 0),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE INDEX idx_order_items_order ON order_items (order_id);

-- ---------------------------------------------------------------------
-- order_status_events — immutable lifecycle audit
-- ---------------------------------------------------------------------
CREATE TABLE order_status_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT       NOT NULL,
    public_id   VARCHAR(36)  NOT NULL,
    from_status VARCHAR(32),
    to_status   VARCHAR(32)  NOT NULL,
    note        VARCHAR(300),
    created_at  TIMESTAMPTZ  NOT NULL,

    CONSTRAINT uk_order_status_events_public_id UNIQUE (public_id),
    CONSTRAINT fk_order_status_event_order FOREIGN KEY (order_id)
        REFERENCES orders (id) ON DELETE CASCADE
);

CREATE INDEX idx_order_events_order ON order_status_events (order_id, created_at);

-- ---------------------------------------------------------------------
-- rider_availability — explicit online/offline state per approved rider
-- ---------------------------------------------------------------------
CREATE TABLE rider_availability (
    user_id     BIGINT      PRIMARY KEY,
    online      BOOLEAN     NOT NULL DEFAULT FALSE,
    updated_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_rider_availability_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE
);
