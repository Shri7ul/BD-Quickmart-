-- =====================================================================
-- BD QuickMart — V1: initial PostgreSQL (Supabase) auth schema
-- ---------------------------------------------------------------------
-- Fresh database only. No legacy MySQL data is migrated.
-- Applied by Flyway as a SEPARATE step with a DDL-capable migration role;
-- the runtime application connects with a least-privilege DML-only role.
--
-- Portability notes (see docs/development/CLOUD_MIGRATION_PLAN.md §3):
--   * Internal PKs stay BIGINT IDENTITY to match GenerationType.IDENTITY.
--   * External IDs (public_id, family_id) are application-generated UUID v4
--     strings stored as VARCHAR(36); no pgcrypto/uuid extension is required.
--   * All timestamps are TIMESTAMPTZ (UTC). hibernate.jdbc.time_zone=UTC
--     binds java.time.Instant values; presentation renders Asia/Dhaka.
--
-- Normalisation / uniqueness contract (requirement §6):
--   * Email  : the application stores trim().toLowerCase(Locale.ROOT).
--   * Phone  : the application stores trim() ONLY (case is not changed).
--   * MySQL utf8mb4_unicode_ci was case- AND accent-insensitive. We do NOT
--     reproduce accent-insensitivity (no citext / ICU non-deterministic
--     collation / unaccent): those requirements are not established. Instead
--     we define CASE-insensitive uniqueness explicitly with functional unique
--     indexes on lower(email) and lower(phone), in addition to plain UNIQUE
--     constraints. lower() is case-folding only, never accent-folding.
-- =====================================================================

SET search_path = public;

-- ---------------------------------------------------------------------
-- users
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      VARCHAR(36)  NOT NULL,
    email          VARCHAR(255) NOT NULL,
    phone          VARCHAR(32)  NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    full_name      VARCHAR(120) NOT NULL,
    role           VARCHAR(32)  NOT NULL,
    status         VARCHAR(24)  NOT NULL,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    deleted_at     TIMESTAMPTZ,

    CONSTRAINT uk_users_public_id UNIQUE (public_id),
    CONSTRAINT uk_users_email     UNIQUE (email),
    CONSTRAINT uk_users_phone     UNIQUE (phone),
    -- The six canonical roles and four account states are code-defined enums;
    -- the CHECK constraints are the database-level guard (no roles lookup
    -- table is seeded).
    CONSTRAINT ck_users_role CHECK (role IN
        ('CUSTOMER','RIDER','ADMIN','SUPER_ADMIN','STORE_MANAGER','INVENTORY_OPERATOR')),
    CONSTRAINT ck_users_status CHECK (status IN
        ('ACTIVE','PENDING','REJECTED','DISABLED'))
);

-- Explicit, case-insensitive uniqueness (defence-in-depth for direct inserts
-- and concurrent registrations). NOT accent-insensitive by design.
CREATE UNIQUE INDEX uk_users_email_lower ON users (lower(email));
CREATE UNIQUE INDEX uk_users_phone_lower ON users (lower(phone));

-- Serves AuthService.pendingRiders() / UserRepository.findAllByRoleAndStatus().
CREATE INDEX idx_users_role_status ON users (role, status);

-- ---------------------------------------------------------------------
-- refresh_tokens
-- ---------------------------------------------------------------------
-- Only the SHA-256 hex hash of each raw refresh token is stored. Tokens from
-- one login session share family_id; replay of a revoked token revokes the
-- whole family. Rotation is serialised by @Lock(PESSIMISTIC_WRITE) which
-- renders as SELECT ... FOR UPDATE on PostgreSQL.
CREATE TABLE refresh_tokens (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash       VARCHAR(64) NOT NULL,
    family_id        VARCHAR(36) NOT NULL,
    user_id          BIGINT      NOT NULL,
    expires_at       TIMESTAMPTZ NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL,
    revoked_at       TIMESTAMPTZ,
    replaced_by_hash VARCHAR(64),
    version          BIGINT      NOT NULL DEFAULT 0,

    CONSTRAINT uk_refresh_token_hash UNIQUE (token_hash),
    -- Rows are soft-deleted, never hard-deleted, so RESTRICT preserves history.
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE INDEX idx_refresh_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_user   ON refresh_tokens (user_id);
-- Partial index supports the replay-detection query (live family members).
CREATE INDEX idx_refresh_family_live
    ON refresh_tokens (family_id) WHERE revoked_at IS NULL;
