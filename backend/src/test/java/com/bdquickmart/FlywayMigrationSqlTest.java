package com.bdquickmart;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.stream.Collectors;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Always-on structural validation of the versioned Flyway migration. It does
 * not need a database (so it runs even where Docker/Testcontainers are
 * unavailable) and guards against accidentally reintroducing MySQL syntax or
 * dropping a required constraint/index. The migration is applied to a REAL
 * PostgreSQL instance by {@link PostgresMigrationIntegrationTest}.
 */
@DisplayName("Flyway V1 migration — structural validation")
class FlywayMigrationSqlTest {

    private String sql() throws Exception {
        try (InputStream in = getClass().getResourceAsStream(
                "/db/migration/V1__init_auth_schema.sql")) {
            assertNotNull(in, "V1__init_auth_schema.sql must be on the classpath");
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    /** Strip SQL line comments so negative assertions inspect real DDL only. */
    private String code(String sql) {
        return sql.lines()
                .map(line -> line.replaceAll("--.*$", ""))
                .collect(Collectors.joining("\n"));
    }

    @Test
    @DisplayName("V1 uses PostgreSQL-native DDL and contains no MySQL artifacts")
    void v1UsesPostgresDdl() throws Exception {
        String ddl = code(sql());
        assertTrue(ddl.contains("CREATE TABLE users"));
        assertTrue(ddl.contains("CREATE TABLE refresh_tokens"));
        assertTrue(ddl.contains("GENERATED BY DEFAULT AS IDENTITY"));
        assertTrue(ddl.contains("TIMESTAMPTZ"));
        assertTrue(ddl.contains("ON DELETE RESTRICT"));
        assertFalse(ddl.contains("AUTO_INCREMENT"), "no MySQL AUTO_INCREMENT");
        assertFalse(ddl.contains("utf8mb4"), "no MySQL charset/collation");
        assertFalse(ddl.contains("ENGINE"), "no MySQL ENGINE clause");
        assertFalse(ddl.contains("`"), "no MySQL backtick quoting");
    }

    @Test
    @DisplayName("V1 defines every constraint, index, role and status")
    void v1DefinesAllObjects() throws Exception {
        String ddl = code(sql());
        for (String object : List.of(
                "uk_users_public_id", "uk_users_email", "uk_users_phone",
                "uk_users_email_lower", "uk_users_phone_lower", "idx_users_role_status",
                "uk_refresh_token_hash", "fk_refresh_user", "idx_refresh_family",
                "idx_refresh_user", "idx_refresh_family_live",
                "ck_users_role", "ck_users_status")) {
            assertTrue(ddl.contains(object), "missing DB object: " + object);
        }
        assertTrue(ddl.contains("lower(email)"));
        assertTrue(ddl.contains("lower(phone)"));
        assertTrue(ddl.contains("WHERE revoked_at IS NULL"), "partial live-family index missing");

        for (String role : List.of("CUSTOMER", "RIDER", "ADMIN", "SUPER_ADMIN",
                "STORE_MANAGER", "INVENTORY_OPERATOR")) {
            assertTrue(ddl.contains("'" + role + "'"), "missing role in CHECK: " + role);
        }
        for (String status : List.of("ACTIVE", "PENDING", "REJECTED", "DISABLED")) {
            assertTrue(ddl.contains("'" + status + "'"), "missing status in CHECK: " + status);
        }
    }

    @Test
    @DisplayName("V1 does NOT introduce accent-insensitive behaviour")
    void v1HasNoAccentInsensitiveBehaviour() throws Exception {
        String ddl = code(sql());
        assertFalse(ddl.contains("citext"), "citext not used");
        assertFalse(ddl.contains("unaccent"), "unaccent not used");
        assertFalse(ddl.contains("COLLATE"), "no non-deterministic ICU collation");
    }
}
